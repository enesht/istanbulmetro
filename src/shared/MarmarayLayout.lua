-- Tünel: Yenikapı 21 m, Sirkeci 45 m, batırma tüp 7.6 m (tek eleman, iki hat), Üsküdar 26 m eksen aralığı.
function M.smoothstep(t) t = math.clamp(t, 0, 1) return t * t * (3 - 2 * t) end
function M.track2Offset(s)
	local P = M.Track2
	if s <= P[1][1] then return P[1][2] end
	for i = 1, #P - 1 do
		local a, b = P[i], P[i + 1]
		if s <= b[1] then return a[2] + (b[2] - a[2]) * M.smoothstep((s - a[1]) / (b[1] - a[1])) end
	end
	return P[#P][2]
end
function M.hasMainLine(s)
	for _, r in ipairs(M.MainLineRanges) do if s >= r[1] and s <= r[2] then return true end end
	return false
end
return M